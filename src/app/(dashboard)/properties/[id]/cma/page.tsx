import { notFound } from "next/navigation";
import { demoProperties, demoCMARecords, formatCurrency } from "@/lib/demo-data";
import { Icon } from "@/components/shared/icon";
import { PrintButton } from "./print-button";

export default async function CmaReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const property = demoProperties.find((item) => item.id === id);
  if (!property) notFound();

  const cma = demoCMARecords.filter((item) => item.property_id === id);

  return (
    <div style={{ padding: "40px", maxWidth: 800, margin: "0 auto", background: "white", minHeight: "100vh", color: "black" }}>
      <div className="no-print" style={{ marginBottom: 24, display: "flex", justifyContent: "space-between", alignItems: "center" }}>
        <a href={`/properties`} style={{ color: "var(--pg-text-dim)", textDecoration: "none", fontSize: 14 }}>&larr; Back to Property</a>
        <PrintButton />
      </div>

      <div className="print-area">
        <header style={{ borderBottom: "2px solid black", paddingBottom: 16, marginBottom: 32 }}>
          <h1 style={{ margin: "0 0 8px", fontSize: 28, fontWeight: 700 }}>Comparable Market Analysis</h1>
          <div style={{ fontSize: 16, color: "#444" }}>{property.canonical_address}</div>
        </header>

        <section style={{ marginBottom: 32 }}>
          <h2 style={{ fontSize: 20, borderBottom: "1px solid #eee", paddingBottom: 8, marginBottom: 16 }}>Property Overview</h2>
          <div style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 16 }}>
            <div><strong>Guide Price:</strong> {formatCurrency(property.listing_price)}</div>
            <div><strong>Bedrooms:</strong> {property.bedrooms}</div>
            <div><strong>Bathrooms:</strong> {property.bathrooms}</div>
            <div><strong>Car Spaces:</strong> {property.car_spaces}</div>
          </div>
          <div style={{ marginTop: 16 }}>
            <strong>Description:</strong>
            <p style={{ fontSize: 14, lineHeight: 1.6, color: "#333", marginTop: 8 }}>{property.raw_data.description}</p>
          </div>
        </section>

        <section style={{ marginBottom: 32 }}>
          <h2 style={{ fontSize: 20, borderBottom: "1px solid #eee", paddingBottom: 8, marginBottom: 16 }}>Comparable Sales</h2>
          {cma.length > 0 ? (
            <table style={{ width: "100%", borderCollapse: "collapse", fontSize: 14 }}>
              <thead>
                <tr style={{ borderBottom: "2px solid #ccc", textAlign: "left" }}>
                  <th style={{ padding: "10px 8px" }}>Address</th>
                  <th style={{ padding: "10px 8px" }}>Sale Price</th>
                  <th style={{ padding: "10px 8px" }}>Date</th>
                  <th style={{ padding: "10px 8px" }}>Distance</th>
                </tr>
              </thead>
              <tbody>
                {cma.map((record) => (
                  <tr key={record.id} style={{ borderBottom: "1px solid #eee" }}>
                    <td style={{ padding: "10px 8px" }}>{record.comparable_address}</td>
                    <td style={{ padding: "10px 8px", fontWeight: 600 }}>{formatCurrency(record.sale_price)}</td>
                    <td style={{ padding: "10px 8px" }}>{record.sale_date}</td>
                    <td style={{ padding: "10px 8px" }}>{record.distance_km}km</td>
                  </tr>
                ))}
              </tbody>
            </table>
          ) : (
            <p style={{ fontSize: 14, color: "#666" }}>No comparable sales records found.</p>
          )}
        </section>
        
        <footer style={{ marginTop: 64, paddingTop: 16, borderTop: "1px solid #ccc", fontSize: 12, color: "#666", textAlign: "center" }}>
          Generated by antigravity
        </footer>
      </div>

      <style>{`
        @media print {
          body * {
            visibility: hidden;
          }
          .print-area, .print-area * {
            visibility: visible;
          }
          .print-area {
            position: absolute;
            left: 0;
            top: 0;
            width: 100%;
          }
          .no-print {
            display: none !important;
          }
        }
      `}</style>
    </div>
  );
}
