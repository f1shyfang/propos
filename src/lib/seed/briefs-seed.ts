export type BriefSeedOptions = {
  clearExisting?: boolean;
};

export async function seedBuyerBriefs(
  db: NodePgDatabase<typeof schema>,
  options: BriefSeedOptions = {},
): Promise<{ inserted: number; skipped: number }> {
  if (options.clearExisting) {
    await db.delete(schema.buyerBriefsTable);
  }

  let inserted = 0;
  let skipped = 0;

  for (const brief of SEED_BRIEFS) {
    const existing = await db
      .select({ id: schema.buyerBriefsTable.id })
      .from(schema.buyerBriefsTable)
      .where(
        and(
          eq(schema.buyerBriefsTable.clientName, brief.clientName),
          eq(schema.buyerBriefsTable.email, brief.email),
        ),
      )
      .limit(1);

    if (existing.length > 0) {
      skipped++;
      continue;
    }

    await db.insert(schema.buyerBriefsTable).values(brief);
    inserted++;
  }

  return { inserted, skipped };
}
